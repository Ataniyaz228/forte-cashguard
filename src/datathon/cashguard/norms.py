@dataclass(frozen=True)
class Rule:
    title: str
    clause: str
    text: str
    url: str


@dataclass(frozen=True)
class ViolationType:
    code: str
    name: str
    why: str  # why the observation may indicate a violation (no unverified claims)
    rules: tuple[Rule, ...]


